export function getStoredPromptTemplate(): string {
  try {
    const stored = localStorage.getItem(PROMPT_TEMPLATE_KEY);
    if (stored && stored.trim()) return stored;
  } catch {
    // ignore
  }
  return DEFAULT_TRANSLATION_PROMPT;
}

export function saveStoredPromptTemplate(template: string): void {
  try {
    localStorage.setItem(PROMPT_TEMPLATE_KEY, template);
  } catch {
    // ignore
  }
}

export function resetStoredPromptTemplate(): string {
  try {
    localStorage.removeItem(PROMPT_TEMPLATE_KEY);
  } catch {
    // ignore
  }
  return DEFAULT_TRANSLATION_PROMPT;
}
